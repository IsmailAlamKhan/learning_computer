import { describe, expect, it } from 'vitest'
import { act, fireEvent, waitFor } from '@testing-library/react'
import { renderApp } from '../apps/testUtils'

const type = (el: HTMLInputElement, v: string) => fireEvent.change(el, { target: { value: v } })
const enter = (el: HTMLInputElement) => fireEvent.keyDown(el, { key: 'Enter' })

describe('TerminalApp', () => {
  it('shows a banner and the help hint, with the coach ids', () => {
    const rig = renderApp('windows', 'terminal')
    expect(rig.q('terminal-output').textContent).toContain('Windows PowerShell')
    expect(rig.q('terminal-output').textContent).toContain('help লিখে Enter চাপুন')
    expect(rig.q<HTMLInputElement>('terminal-input')).toBeTruthy()
    expect(rig.q('terminal-output').getAttribute('aria-live')).toBe('polite')
    expect(rig.d().wm.windows[0].title).toBe('Terminal')
  })

  it('types a command, Enter runs it, output + event + focus kept', async () => {
    const rig = renderApp('mac', 'terminal')
    const input = rig.q<HTMLInputElement>('terminal-input')
    expect(input.ownerDocument.activeElement).toBe(input)
    type(input, 'mkdir coding')
    enter(input)
    await waitFor(() => expect(rig.d().vfs.resolve('~/coding')).not.toBeNull())
    expect(input.value).toBe('')
    type(input, 'cd coding')
    enter(input)
    await waitFor(() => expect(rig.q('terminal-output').textContent).toContain('anika@Mac ~ % cd coding'))
    await waitFor(() => expect(rig.q('terminal-input').parentElement!.textContent).toContain('anika@Mac coding %'))
    const cmds = rig.bus.log.filter((e) => e.type === 'command')
    expect(cmds.map((c) => (c as { cwd: string }).cwd)).toEqual(['~', '~/coding'])
    await waitFor(() => expect(input.ownerDocument.activeElement).toBe(input))
    type(input, 'pwd')
    enter(input)
    await waitFor(() => expect(rig.q('terminal-output').textContent).toContain('/Users/anika/coding'))
  })

  it('Tab completes, double Tab lists, ArrowUp recalls, Ctrl+C clears the line', async () => {
    const rig = renderApp('windows', 'terminal')
    const input = rig.q<HTMLInputElement>('terminal-input')
    type(input, 'cd Doc')
    fireEvent.keyDown(input, { key: 'Tab' })
    expect(input.value).toBe('cd Documents\\')
    type(input, 'cd D')
    fireEvent.keyDown(input, { key: 'Tab' })
    expect(rig.q('terminal-output').textContent).toContain('Desktop')
    expect(rig.q('terminal-output').textContent).toContain('Downloads')
    type(input, 'echo first')
    enter(input)
    await waitFor(() => expect(rig.q('terminal-output').textContent).toContain('first'))
    type(input, 'echo second')
    enter(input)
    await waitFor(() => expect(rig.q('terminal-output').textContent).toContain('second'))
    fireEvent.keyDown(input, { key: 'ArrowUp' })
    expect(input.value).toBe('echo second')
    fireEvent.keyDown(input, { key: 'ArrowUp' })
    expect(input.value).toBe('echo first')
    fireEvent.keyDown(input, { key: 'ArrowDown' })
    expect(input.value).toBe('echo second')
    fireEvent.keyDown(input, { key: 'ArrowDown' })
    expect(input.value).toBe('')
    type(input, 'half typed')
    fireEvent.keyDown(input, { key: 'c', ctrlKey: true })
    expect(input.value).toBe('')
    expect(rig.q('terminal-output').textContent).toContain('half typed^C')
  })

  it('clear wipes the scrollback; calm styling for errors', async () => {
    const rig = renderApp('mac', 'terminal')
    const input = rig.q<HTMLInputElement>('terminal-input')
    type(input, 'nonsense')
    enter(input)
    await waitFor(() => expect(rig.q('terminal-output').textContent).toContain('command not found'))
    const errLine = [...rig.q('terminal-output').querySelectorAll('div')].find((d) => d.textContent?.includes('command not found'))!
    expect((errLine as HTMLElement).style.color).toBe('rgb(251, 191, 36)')
    type(input, 'clear')
    enter(input)
    await waitFor(() => expect(rig.q('terminal-output').textContent).not.toContain('command not found'))
    expect(rig.q('terminal-output').textContent).not.toContain('Last login')
    type(input, 'x')
    fireEvent.keyDown(input, { key: 'l', ctrlKey: true })
    await act(async () => {})
  })

  it('starts in props.cwd when the folder exists, and works on the shared vfs', async () => {
    const rig = renderApp('windows')
    rig.d().vfs.mkdir(rig.d().vfs.home, 'coding')
    rig.open('terminal', { cwd: '~/coding' })
    const input = rig.q<HTMLInputElement>('terminal-input')
    expect(input.parentElement!.textContent).toContain('PS C:\\Users\\Anika\\coding>')
    type(input, 'echo hi > a.txt')
    enter(input)
    await waitFor(() => expect(rig.d().vfs.resolve('~/coding/a.txt')?.content).toBe('hi\n'))
  })
})
