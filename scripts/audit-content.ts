/**
 * Content audit: measures how text-heavy every screen of every lesson is.
 *   npx tsx scripts/audit-content.ts [--report docs/UX_AUDIT_BEFORE.md]
 * "Screens" for the OLD lesson format: each explanation block, each guided step (instruction/hint/success), each quiz
 * question (question/options/explanation), summary card points and real-world tasks.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { auditLessons, summarize } from './audit-core'
import { ART_NAMES, MOCK_REGIONS } from '../src/ui/illustrations/names'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const words = (t: string | undefined) => (t ?? '').trim().split(/\s+/).filter(Boolean).length
const sentences = (t: string | undefined) => ((t ?? '').match(/[^।?!.]+[।?!.]*/g) ?? []).filter((s) => s.trim()).length

interface Row { module: number; where: string; kind: string; words: number; sentences: number; visual: boolean }

async function loadLessons() {
  const dir = join(root, 'src/content/lessons')
  const files = readdirSync(dir).filter((f) => /^m\d\d\.ts$/.test(f)).sort()
  const out = []
  for (const f of files) out.push((await import(pathToFileURL(join(dir, f)).href)).default)
  return out
}

function oldRows(l: any): Row[] {
  const rows: Row[] = []
  const add = (where: string, kind: string, text: string | undefined, visual = false) => rows.push({ module: l.module, where, kind, words: words(text), sentences: sentences(text), visual })
  ;(l.explanation ?? []).forEach((b: any, i: number) => {
    if (b.kind === 'list') add(`explain #${i + 1}`, 'list', (b.itemsBn ?? []).join(' '))
    else if (b.kind === 'widget') add(`explain #${i + 1}`, 'widget', '', true)
    else if (b.kind === 'code') add(`explain #${i + 1}`, 'code', '', true)
    else add(`explain #${i + 1}`, b.kind, b.textBn)
  })
  const steps = [...(l.steps ?? []), ...((l.chapters ?? []).flatMap((c: any) => c.steps))]
  for (const s of steps) {
    add(`step ${s.id}`, 'instruction', s.explanationBn)
    add(`step ${s.id}`, 'hint', s.hintBn)
    if (s.successMessageBn) add(`step ${s.id}`, 'success', s.successMessageBn)
  }
  for (const q of l.quiz ?? []) {
    add(`quiz ${q.id}`, 'question', q.questionBn)
    add(`quiz ${q.id}`, 'quiz-explain', q.explanationBn)
    for (const o of q.options ?? []) add(`quiz ${q.id}`, 'option', o.textBn)
  }
  ;(l.summaryCard?.pointsBn ?? []).forEach((p: string, i: number) => add(`summary #${i + 1}`, 'summary', p))
  ;(l.realWorld?.tasksBn ?? []).forEach((p: string, i: number) => add(`real-world #${i + 1}`, 'task', p))
  return rows
}

const CAP: Record<string, number> = { instruction: 12, hint: 15, success: 6, question: 20, option: 8, 'quiz-explain': 15, p: 35, analogy: 35, note: 35, list: 35 }

async function loadGlossary() {
  const dir = join(root, 'src/content/glossary')
  const out: any[] = []
  for (const f of readdirSync(dir).filter((f) => /^m\d\d\.ts$/.test(f)).sort()) out.push(...(await import(pathToFileURL(join(dir, f)).href)).default)
  return out
}

/** New (cards) format: enforce the budget; exit code 1 on violations. */
async function mainCards(lessons: any[]) {
  const widgetIds = new Set(readdirSync(join(root, 'src/content/widgets')).filter((f) => f.endsWith('.tsx') && f !== 'index.tsx').map((f) => f.replace('.tsx', '')))
  const res = auditLessons(lessons, { widgetIds, artNames: new Set(ART_NAMES), mockRegions: MOCK_REGIONS as any, glossary: await loadGlossary() })
  const sum = summarize(res.items)
  let md = `# UX content audit\n\nGenerated by \`npm run audit:content\`.\n\n| metric | value |\n|---|---|\n| lessons | ${res.lessons} (${res.legacy.length} not migrated: ${res.legacy.join(', ') || '–'}) |\n| units | ${res.units} |\n| cards (hook + micro) | ${sum.cards} |\n| cards with a visual | ${sum.cardsWithVisual} of ${sum.cards} |\n| average / max words per card | ${sum.cardAvg} / ${sum.cardMax} |\n| hard violations | ${res.violations.length} |\n| tight (over target, under hard cap) | ${res.tight.length} |\n\n## Words by kind\n\n| kind | items | avg | max |\n|---|---|---|---|\n`
  for (const r of sum.rows) md += `| ${r.kind} | ${r.n} | ${r.avg} | ${r.max} |\n`
  if (res.violations.length) {
    md += `\n## Violations\n\n| module | where | rule | detail |\n|---|---|---|---|\n`
    for (const v of res.violations) md += `| ${v.module} | ${v.where} | ${v.rule} | ${v.detail} |\n`
  }
  // appendix: the 20 tightest items (most over their target, still under the hard cap)
  const over = (t: { detail: string; rule: string }) => Number(/(\d+) words/.exec(t.detail)?.[1] ?? 0) - Number(/> (\d+)/.exec(t.rule)?.[1] ?? 18)
  const tight = [...res.tight].sort((a, b) => over(b) - over(a)).slice(0, 20)
  md += `\n## Appendix: tight list (top 20 of ${res.tight.length}; over the target, under the hard cap)\n\n| module | where | rule | detail |\n|---|---|---|---|\n`
  for (const t of tight) md += `| ${t.module} | ${t.where} | ${t.rule} | ${t.detail} |\n`
  // before/after comparison (the 'before' numbers were captured from the old lesson format before the overhaul)
  const beforePath = join(root, 'docs/ux-audit-before.json')
  if (existsSync(beforePath)) {
    const b = JSON.parse(readFileSync(beforePath, 'utf8'))
    const row = (k: string) => sum.rows.find((r) => r.kind === k)
    const ins = row('instruction')
    md += `\n## Before → after (the point of the overhaul)\n\n| metric | before (old format) | after (cards) |\n|---|---|---|\n`
    md += `| explanation unit: avg words | ${b.explainAvgWords} (per paragraph/list block) | ${sum.cardAvg} (per card) |\n`
    md += `| explanation unit: max words | ${b.explainMaxWords} | ${sum.cardMax} |\n`
    md += `| explanation units with a visual | ${b.blocksWithVisual} of ${b.blocksTotal} | ${sum.cardsWithVisual} of ${sum.cards} |\n`
    md += `| guided-step instruction: avg / max words | ${b.instructionAvg} / ${b.instructionMax} | ${ins?.avg} / ${ins?.max} |\n`
    md += `| text items over the hard word caps | ${b.itemsOverCaps} | ${res.violations.length} |\n`
    md += `| lessons × units (decks) | ${b.lessons} long pages | ${res.units} short decks |\n`
  }
  const i = process.argv.indexOf('--report')
  if (i > 0) writeFileSync(join(root, process.argv[i + 1]), md)
  const j = process.argv.indexOf('--json')
  if (j > 0) writeFileSync(join(root, process.argv[j + 1]), JSON.stringify({ ...sum, violations: res.violations.length, tight: res.tight.length, legacy: res.legacy, units: res.units }, null, 2))
  for (const v of res.violations.slice(0, 60)) console.error(`✖ m${v.module} ${v.where}: ${v.rule} (${v.detail})`)
  if (res.violations.length > 60) console.error(`… and ${res.violations.length - 60} more`)
  console.log(`audit: ${res.units} units, ${sum.cards} cards, ${res.violations.length} violations, ${res.tight.length} tight, ${res.legacy.length} lessons not migrated`)
  const allowLegacy = process.argv.includes('--allow-legacy')
  if (res.violations.length > 0 || (res.legacy.length > 0 && !allowLegacy)) process.exit(1)
}

async function main() {
  const lessons = await loadLessons()
  if (!process.argv.includes('--before')) return mainCards(lessons)
  const all = lessons.flatMap(oldRows)
  const text = all.filter((r) => r.words > 0)
  const over = text.filter((r) => CAP[r.kind] && r.words > CAP[r.kind])
  const avg = (a: Row[]) => (a.length ? (a.reduce((s, r) => s + r.words, 0) / a.length).toFixed(1) : '0')
  const byKind = new Map<string, Row[]>()
  for (const r of text) byKind.set(r.kind, [...(byKind.get(r.kind) ?? []), r])
  const expl = text.filter((r) => ['p', 'analogy', 'note', 'list'].includes(r.kind))
  const blocks = all.filter((r) => r.where.startsWith('explain'))
  const noVisual = blocks.filter((r) => !r.visual)
  let md = `# UX audit — before the overhaul\n\nGenerated by \`scripts/audit-content.ts\` (old lesson format). Word = whitespace-separated token.\n\n`
  md += `## Summary\n\n| metric | value |\n|---|---|\n| lessons | ${lessons.length} |\n| measured text items | ${text.length} |\n| explanation text blocks | ${expl.length} (avg ${avg(expl)} words, max ${Math.max(...expl.map((r) => r.words))}) |\n| explanation blocks with a visual | ${blocks.length - noVisual.length} of ${blocks.length} |\n| items over the new word caps | ${over.length} |\n\n`
  md += `## Average / max words by kind\n\n| kind | items | avg words | max words | cap |\n|---|---|---|---|---|\n`
  for (const [k, a] of [...byKind.entries()].sort()) md += `| ${k} | ${a.length} | ${avg(a)} | ${Math.max(...a.map((r) => r.words))} | ${CAP[k] ?? '–'} |\n`
  md += `\n## Per module: explanation words (all explanation blocks) and steps\n\n| module | explain blocks | explain words | longest block | steps | avg step words | quiz Qs |\n|---|---|---|---|---|---|---|\n`
  for (const l of lessons) {
    const rs = oldRows(l)
    const ex = rs.filter((r) => r.where.startsWith('explain'))
    const st = rs.filter((r) => r.kind === 'instruction')
    md += `| ${l.module} | ${ex.length} | ${ex.reduce((s, r) => s + r.words, 0)} | ${Math.max(0, ...ex.map((r) => r.words))} | ${st.length} | ${avg(st)} | ${(l.quiz ?? []).length} |\n`
  }
  md += `\n## Worst 40 screens (most words)\n\n| # | module | where | kind | words | sentences |\n|---|---|---|---|---|---|\n`
  text.sort((a, b) => b.words - a.words).slice(0, 40).forEach((r, i) => (md += `| ${i + 1} | ${r.module} | ${r.where} | ${r.kind} | ${r.words} | ${r.sentences} |\n`))
  const i = process.argv.indexOf('--report')
  if (i > 0) writeFileSync(join(root, process.argv[i + 1]), md)
  else console.log(md)
  const j = process.argv.indexOf('--json')
  if (j > 0) {
    const avgW = (a: Row[]) => (a.length ? +(a.reduce((s, r) => s + r.words, 0) / a.length).toFixed(1) : 0)
    writeFileSync(
      join(root, process.argv[j + 1]),
      JSON.stringify({ explainBlocks: expl.length, explainAvgWords: avgW(expl), explainMaxWords: Math.max(...expl.map((r) => r.words)), blocksWithVisual: blocks.length - noVisual.length, blocksTotal: blocks.length, instructionAvg: avgW(text.filter((r) => r.kind === 'instruction')), instructionMax: Math.max(...text.filter((r) => r.kind === 'instruction').map((r) => r.words)), itemsOverCaps: over.length, lessons: lessons.length }, null, 2),
    )
  }
}
main()
